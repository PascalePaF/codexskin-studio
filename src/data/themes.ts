export function getThemeById(id: string): SkinTheme | undefined {
  return PRESET_THEMES.find((theme) => theme.id === id);
}

export function getPairThemes(pair: ThemePair): { light: SkinTheme; dark: SkinTheme } {
  const light = getThemeById(pair.lightThemeId);
  const dark = getThemeById(pair.darkThemeId);
  if (!light || !dark) throw new Error(`主题组合 ${pair.id} 缺少配色`);
  return { light, dark };
}
